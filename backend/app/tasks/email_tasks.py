async def send_flag_escalation(employee_email: str, employee_name: str, note: str):
    hr_email = getattr(settings, "HR_ESCALATION_EMAIL", settings.SMTP_FROM_EMAIL)
    subject = f"URGENT Notice: Activity Escalation - {employee_name}"
    content = f"""
        <p>Dear {employee_name} and Human Resources,</p>
        <p>Continuous or severe anomalous patterns have been validated on the Sentinel network. This constitutes a direct breach of integrity guidelines.</p>
        <p><strong>This incident has been formally escalated for administrative review.</strong></p>
        <div class="box">
            <p style="margin:0;"><span class="label" style="width:130px;">Escalation Note:</span> {note}</p>
        </div>
        <p>A senior Human Resources representative will contact you shortly to schedule a formal review of this incident.</p>
    """
    html = _get_base_template("Formal Incident Escalation", content, color="#dc2626")

    await asyncio.to_thread(_send_email_sync, employee_email, subject, html)
    if hr_email and hr_email != employee_email:
        await asyncio.to_thread(_send_email_sync, hr_email, subject, html)
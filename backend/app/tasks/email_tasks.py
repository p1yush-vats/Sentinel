def _send_email_sync(to_email: str, subject: str, html_body: str):
    """Synchronous core wrapped by asyncio.to_thread"""
    if not settings.SMTP_HOST or not settings.SMTP_USER:
        logger.warning(f"SMTP not configured — skipping email to {to_email}")
        return

    msg = EmailMessage()
    msg['Subject'] = subject
    msg['From'] = settings.SMTP_FROM_EMAIL or settings.SMTP_USER
    msg['To'] = to_email
    msg.add_alternative(html_body, subtype='html')

    try:
        with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT) as server:
            server.starttls()
            server.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
            server.send_message(msg)
            logger.info(f"Email dispatched to {to_email} — subject: '{subject}'")
    except Exception as e:
        logger.error(f"Failed to send email to {to_email}: {e}")


async def send_task_assignment(employee_email: str, employee_name: str, task_title: str, priority: str):
    subject = f"Notice: Official Task Assignment - {task_title}"
    content = f"""
        <p>Dear {employee_name},</p>
        <p>This is to formally notify you that a new administrative task has been assigned to your queue via the Sentinel system.</p>
        <div class="box">
            <p style="margin:0 0 10px 0;"><span class="label">Task ID:</span> {task_title}</p>
            <p style="margin:0;"><span class="label">Priority:</span> <span style="text-transform: uppercase;">{priority}</span></p>
        </div>
        <p>Please launch your Sentinel Desktop Application at your earliest convenience to review the full details and specifications of this assignment.</p>
    """
    html = _get_base_template("Task Assignment Notice", content, color="#4f46e5")
    await asyncio.to_thread(_send_email_sync, employee_email, subject, html)


